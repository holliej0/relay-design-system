// Turns tokens/tokens.json into src/styles/tokens.css (CSS custom properties)
// and src/tokens.ts (typed values for JS use). Run: npm run tokens
import { readFileSync, writeFileSync } from "node:fs";

const t = JSON.parse(readFileSync(new URL("../tokens/tokens.json", import.meta.url)));
const color = (ref) => {
  const [scale, step] = ref.split(".");
  const v = t.primitive.color[scale]?.[step];
  if (!v) throw new Error(`Unknown color reference: ${ref}`);
  return v;
};

const lines = ["/* Generated by scripts/build-tokens.mjs. Edit tokens/tokens.json instead. */", ":root {"];
for (const [scale, steps] of Object.entries(t.primitive.color))
  for (const [step, hex] of Object.entries(steps)) lines.push(`  --rds-color-${scale}-${step}: ${hex};`);
for (const group of ["space", "radius", "shadow", "motion"])
  for (const [k, v] of Object.entries(t.primitive[group])) lines.push(`  --rds-${group}-${k}: ${v};`);
for (const [k, v] of Object.entries(t.primitive.font.family)) lines.push(`  --rds-font-${k}: ${v};`);
for (const [k, v] of Object.entries(t.primitive.font.size)) lines.push(`  --rds-text-${k}: ${v};`);
for (const [k, v] of Object.entries(t.primitive.font.lineHeight)) lines.push(`  --rds-leading-${k}: ${v};`);
for (const [k, v] of Object.entries(t.primitive.font.weight)) lines.push(`  --rds-weight-${k}: ${v};`);
const semantic = (mode) =>
  Object.entries(t.semantic[mode]).map(([k, ref]) => {
    const [scale, step] = ref.split(".");
    return `  --rds-${k}: var(--rds-color-${scale}-${step});`;
  });
lines.push(...semantic("light"), "  color-scheme: light;", "}", "", '[data-theme="dark"] {', ...semantic("dark"), "  color-scheme: dark;", "}", "");
lines.push("@media (prefers-color-scheme: dark) {", '  :root:not([data-theme="light"]) {', ...semantic("dark").map((l) => "  " + l), "    color-scheme: dark;", "  }", "}", "");
writeFileSync(new URL("../src/styles/tokens.css", import.meta.url), lines.join("\n"));

const resolved = Object.fromEntries(
  ["light", "dark"].map((m) => [m, Object.fromEntries(Object.entries(t.semantic[m]).map(([k, r]) => [k, color(r)]))])
);
writeFileSync(
  new URL("../src/tokens.ts", import.meta.url),
  `// Generated by scripts/build-tokens.mjs. Edit tokens/tokens.json instead.\n` +
    `export const primitive = ${JSON.stringify(t.primitive, null, 2)} as const;\n\n` +
    `export const semantic = ${JSON.stringify(resolved, null, 2)} as const;\n\n` +
    `export type SemanticToken = keyof typeof semantic.light;\n`
);
console.log(`Wrote ${Object.keys(t.semantic.light).length} semantic tokens for light and dark.`);
